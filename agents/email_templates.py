"""
Email templates for customer communication agent
"""

def create_hvac_status_email(customer_info, hvac_status, scheduled_maintenance):
    """Create comprehensive HVAC status email"""
    
    customer_name = customer_info.get('name', 'Valued Customer')
    
    # Parse HVAC status
    temperature = hvac_status.get('temperature', 'N/A')
    pressure = hvac_status.get('pressure', 'N/A')
    humidity = hvac_status.get('humidity', 'N/A')
    power_consumption = hvac_status.get('powerConsumption', 'N/A')
    status = hvac_status.get('status', 'unknown')
    last_updated = hvac_status.get('lastUpdated', 'N/A')
    
    # Status indicator
    status_emoji = "✅" if status == "normal" else "⚠️" if status == "needs_attention" else "🔴"
    
    # Build maintenance section
    maintenance_section = ""
    if scheduled_maintenance and len(scheduled_maintenance) > 0:
        maintenance_section = "\n📅 UPCOMING SCHEDULED MAINTENANCE:\n"
        maintenance_section += "=" * 40 + "\n"
        
        for job in scheduled_maintenance:
            maintenance_section += f"""
• {job.get('type', 'Maintenance')}
  Date: {job.get('scheduledDate', 'TBD')}
  Technician: {job.get('technician', 'TBD')}
  Description: {job.get('description', 'Standard maintenance')}
"""
    else:
        maintenance_section = "\n📅 No scheduled maintenance at this time.\n"
    
    # Create email content
    subject = f"HVAC System Status Update - {customer_name}"
    
    message = f"""Dear {customer_name},

This is your regular HVAC system status update from our Field Service Management team.

🏠 CURRENT SYSTEM STATUS: {status_emoji} {status.upper()}
=" * 50

📊 System Metrics (as of {last_updated}):
• Temperature: {temperature}°F
• Pressure: {pressure} PSI  
• Humidity: {humidity}%
• Power Consumption: {power_consumption}W

{maintenance_section}

📞 CONTACT INFORMATION:
If you have any questions or concerns about your HVAC system, please don't hesitate to contact us:
• Phone: (555) 123-HVAC
• Email: support@fsm-hvac.com
• Emergency Line: (555) 911-HVAC (24/7)

Thank you for choosing our HVAC maintenance services. We're committed to keeping your system running efficiently and your home comfortable.

Best regards,
FSM HVAC Service Team

---
This is an automated notification from your HVAC monitoring system.
To update your notification preferences, please contact our customer service team.
"""
    
    return subject, message

def create_alert_email(customer_info, alert_details, scheduled_maintenance):
    """Create alert email for system issues"""
    
    customer_name = customer_info.get('name', 'Valued Customer')
    alert_type = alert_details.get('type', 'System Alert')
    severity = alert_details.get('severity', 'medium')
    description = alert_details.get('description', 'System requires attention')
    
    # Severity indicators
    severity_emoji = "🔴" if severity == "high" else "⚠️" if severity == "medium" else "🟡"
    
    subject = f"🚨 HVAC Alert: {alert_type} - {customer_name}"
    
    message = f"""Dear {customer_name},

{severity_emoji} HVAC SYSTEM ALERT {severity_emoji}

We've detected an issue with your HVAC system that requires attention:

🔍 ALERT DETAILS:
• Type: {alert_type}
• Severity: {severity.upper()}
• Description: {description}
• Detected: {alert_details.get('timestamp', 'Recently')}

🔧 RECOMMENDED ACTION:
{alert_details.get('recommended_action', 'Please contact our service team for inspection and repair.')}

📅 SCHEDULED MAINTENANCE:
{f"Good news! You have maintenance scheduled for {scheduled_maintenance[0].get('scheduledDate')} which may address this issue." if scheduled_maintenance else "We recommend scheduling a service appointment as soon as possible."}

📞 IMMEDIATE ASSISTANCE:
For urgent issues or to schedule service:
• Emergency Line: (555) 911-HVAC (24/7)
• Regular Service: (555) 123-HVAC
• Email: support@fsm-hvac.com

Our certified technicians are standing by to help resolve this issue quickly and efficiently.

Best regards,
FSM HVAC Service Team

---
This alert was generated by your automated HVAC monitoring system.
"""
    
    return subject, message

def create_maintenance_reminder_email(customer_info, scheduled_maintenance):
    """Create maintenance reminder email"""
    
    customer_name = customer_info.get('name', 'Valued Customer')
    
    subject = f"🔧 Maintenance Reminder - {customer_name}"
    
    # Build maintenance details
    maintenance_details = ""
    if scheduled_maintenance and len(scheduled_maintenance) > 0:
        next_maintenance = scheduled_maintenance[0]
        maintenance_details = f"""
📅 NEXT SCHEDULED MAINTENANCE:
• Date: {next_maintenance.get('scheduledDate', 'TBD')}
• Type: {next_maintenance.get('type', 'Routine Maintenance')}
• Technician: {next_maintenance.get('technician', 'TBD')}
• Description: {next_maintenance.get('description', 'Standard maintenance procedures')}

"""
        
        if len(scheduled_maintenance) > 1:
            maintenance_details += "📋 ADDITIONAL UPCOMING MAINTENANCE:\n"
            for job in scheduled_maintenance[1:]:
                maintenance_details += f"• {job.get('scheduledDate')}: {job.get('type')}\n"
    
    message = f"""Dear {customer_name},

This is a friendly reminder about your upcoming HVAC system maintenance.

{maintenance_details}

🔧 WHAT TO EXPECT:
• System inspection and performance check
• Filter replacement (if needed)
• Cleaning of key components
• Safety and efficiency testing
• Detailed service report

📋 PREPARATION:
• Ensure clear access to your HVAC unit
• Remove any items stored near the system
• Make note of any concerns or unusual noises
• Have your service history available

📞 QUESTIONS OR RESCHEDULING:
• Phone: (555) 123-HVAC
• Email: support@fsm-hvac.com
• Online: www.fsm-hvac.com/schedule

Regular maintenance helps ensure optimal performance, energy efficiency, and extends the life of your HVAC system.

Thank you for being a valued customer!

Best regards,
FSM HVAC Service Team

---
Automated reminder from your HVAC maintenance schedule.
"""
    
    return subject, message
